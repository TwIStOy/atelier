import * as fs from "node:fs";
import * as path from "node:path";
import { atomicWriteFile, readJsonl } from "./atomic.ts";
import { parseFrontmatter } from "./frontmatter.ts";
import { MANIFEST_FILENAME, type SourcePacketManifest, type SourceType } from "./manifest.ts";
import { extractWikilinkTargets } from "./wikilinks.ts";

export const REGISTRY_SCHEMA_VERSION = 1;
export const BACKLINKS_SCHEMA_VERSION = 1;
export const EVENTS_FILENAME = "events.jsonl";

const EXCERPT_MAX = 160;
const KNOWN_PAGE_TYPE_ORDER = ["source", "concept", "entity", "synthesis", "analysis"] as const;

export interface PageRegistryEntry {
  id: string;
  path: string;
  title: string | null;
  type: string | null;
  aliases: string[];
  sources: string[];
  links: string[];
  brokenLinks: string[];
  headings: string[];
  excerpt: string;
  mtimeMs: number | null;
}

export interface SourceRegistryEntry {
  id: string;
  path: string;
  originType: SourceType;
  title: string | null;
  url?: string;
  originPath?: string;
  contentHash: string;
  ingestStatus: SourcePacketManifest["ingest"]["status"];
  capturedAt: string;
}

export interface RegistryDoc {
  schemaVersion: typeof REGISTRY_SCHEMA_VERSION;
  builtAt: string;
  vault: string;
  pages: PageRegistryEntry[];
  sources: SourceRegistryEntry[];
}

export interface BacklinksDoc {
  schemaVersion: typeof BACKLINKS_SCHEMA_VERSION;
  builtAt: string;
  vault: string;
  backlinks: Record<string, string[]>;
}

export interface RebuildOptions {
  now?: () => Date;
}

export interface RebuildResult {
  vault: string;
  pages: number;
  sources: number;
  backlinks: number;
  events: number;
  written: string[];
}

export function buildRegistry(vaultRoot: string, opts: RebuildOptions = {}): RegistryDoc {
  const builtAt = (opts.now ?? (() => new Date()))().toISOString();
  const pages = collectPages(vaultRoot);
  const sources = collectSources(vaultRoot);
  return { schemaVersion: REGISTRY_SCHEMA_VERSION, builtAt, vault: vaultRoot, pages, sources };
}

export function buildBacklinks(registry: RegistryDoc, opts: RebuildOptions = {}): BacklinksDoc {
  const builtAt = (opts.now ?? (() => new Date()))().toISOString();
  const backlinks: Record<string, string[]> = {};
  for (const page of registry.pages) {
    for (const target of page.links) {
      if (target === page.id) continue;
      const list = getOrInitRecord(backlinks, target);
      list.push(page.id);
    }
  }
  for (const key of Object.keys(backlinks)) {
    backlinks[key] = [...new Set(backlinks[key]!)].sort();
  }
  return { schemaVersion: BACKLINKS_SCHEMA_VERSION, builtAt, vault: registry.vault, backlinks };
}

export function renderIndexMd(registry: RegistryDoc): string {
  const lines: string[] = [
    "# Wiki Index",
    "",
    "> Auto-generated by `wiki_rebuild_meta` from `raw/` + `wiki/`. Do not edit directly.",
    "",
    `- Pages: ${registry.pages.length}`,
    `- Sources: ${registry.sources.length}`,
  ];

  if (registry.sources.length > 0) {
    lines.push("", "## Sources");
    for (const source of registry.sources) {
      const title = source.title ?? "(untitled)";
      lines.push(`- \`${source.id}\` — ${title} *(${source.originType}, ${source.ingestStatus})*`);
    }
  }

  if (registry.pages.length > 0) {
    lines.push("", "## Pages");
    for (const group of groupPagesByType(registry.pages)) {
      lines.push("", `### ${group.label} (${group.pages.length})`);
      for (const page of group.pages) {
        lines.push(`- [[${page.id}]] — ${page.title ?? page.id}`);
      }
    }
  }

  return `${lines.join("\n")}\n`;
}

export function renderLogMd(events: unknown[]): string {
  return renderLog(events).md;
}

function renderLog(events: unknown[]): { md: string; count: number } {
  const header = ["# Wiki Log", "", "> Auto-generated from `meta/events.jsonl`."];
  if (events.length === 0) return { md: `${header.join("\n")}\n`, count: 0 };

  const groups = new Map<string, RenderedEvent[]>();
  let count = 0;
  for (const raw of events) {
    const rendered = renderEventLine(raw);
    if (!rendered) continue;
    count += 1;
    getOrInitMap(groups, rendered.date, () => []).push(rendered);
  }

  const lines = [...header];
  for (const date of [...groups.keys()].sort()) {
    lines.push("", `## ${date}`);
    for (const entry of groups.get(date)!) {
      lines.push(`- ${entry.time} ${entry.text}`);
    }
  }
  return { md: `${lines.join("\n")}\n`, count };
}

export function rebuildMeta(vaultRoot: string, opts: RebuildOptions = {}): RebuildResult {
  const layout = metaLayout(vaultRoot);
  const registry = buildRegistry(vaultRoot, opts);
  const backlinks = buildBacklinks(registry, opts);
  const events = readEvents(layout.events);
  const indexMd = renderIndexMd(registry);
  const log = renderLog(events);

  atomicWriteFile(layout.registry, `${JSON.stringify(registry, null, 2)}\n`);
  atomicWriteFile(layout.backlinks, `${JSON.stringify(backlinks, null, 2)}\n`);
  atomicWriteFile(layout.index, indexMd);
  atomicWriteFile(layout.log, log.md);

  return {
    vault: vaultRoot,
    pages: registry.pages.length,
    sources: registry.sources.length,
    backlinks: Object.keys(backlinks.backlinks).length,
    events: log.count,
    written: [
      relVault(vaultRoot, layout.registry),
      relVault(vaultRoot, layout.backlinks),
      relVault(vaultRoot, layout.index),
      relVault(vaultRoot, layout.log),
    ].sort(),
  };
}

interface MetaLayout {
  registry: string;
  backlinks: string;
  index: string;
  log: string;
  events: string;
}

function metaLayout(vaultRoot: string): MetaLayout {
  const meta = path.join(vaultRoot, "meta");
  return {
    registry: path.join(meta, "registry.json"),
    backlinks: path.join(meta, "backlinks.json"),
    index: path.join(meta, "index.md"),
    log: path.join(meta, "log.md"),
    events: path.join(meta, EVENTS_FILENAME),
  };
}

function relVault(vaultRoot: string, absPath: string): string {
  return toPosix(path.relative(vaultRoot, absPath));
}

function toPosix(p: string): string {
  return p.split(path.sep).join("/");
}

interface WorkingPage {
  id: string;
  path: string;
  title: string | null;
  type: string | null;
  aliases: string[];
  sources: string[];
  headings: string[];
  excerpt: string;
  mtimeMs: number | null;
  rawLinks: string[];
}

function collectPages(vaultRoot: string): PageRegistryEntry[] {
  const wikiDir = path.join(vaultRoot, "wiki");
  const working: WorkingPage[] = [];
  for (const file of listMarkdownFiles(wikiDir)) {
    const page = buildWorkingPage(vaultRoot, wikiDir, file);
    if (page) working.push(page);
  }
  working.sort((a, b) => a.id.localeCompare(b.id));
  return resolveLinks(working);
}

function listMarkdownFiles(root: string): string[] {
  if (!fs.existsSync(root)) return [];
  const out: string[] = [];
  const stack: string[] = [root];
  while (stack.length > 0) {
    const dir = stack.pop()!;
    for (const name of fs.readdirSync(dir)) {
      const abs = path.join(dir, name);
      const stat = fs.statSync(abs);
      if (stat.isDirectory()) stack.push(abs);
      else if (stat.isFile() && name.toLowerCase().endsWith(".md")) out.push(abs);
    }
  }
  return out.sort();
}

function buildWorkingPage(vaultRoot: string, wikiDir: string, file: string): WorkingPage | null {
  let content: string;
  try {
    content = fs.readFileSync(file, "utf8");
  } catch {
    return null;
  }
  const { fm, body } = parseFrontmatter(content);
  const relWiki = toPosix(path.relative(wikiDir, file));
  const id = relWiki.replace(/\.md$/i, "");
  let mtimeMs: number | null = null;
  try {
    mtimeMs = fs.statSync(file).mtimeMs;
  } catch {
    mtimeMs = null;
  }
  return {
    id,
    path: toPosix(path.relative(vaultRoot, file)),
    title: fm?.title?.trim() || null,
    type: fm?.type ? fm.type.trim().toLowerCase() : null,
    aliases: cleanStrings(fm?.aliases),
    sources: [...new Set(cleanStrings(fm?.sources))].sort(),
    headings: extractH1Headings(body),
    excerpt: makeExcerpt(body),
    mtimeMs,
    rawLinks: extractWikilinkTargets(body),
  };
}

function resolveLinks(working: WorkingPage[]): PageRegistryEntry[] {
  const idByLower = new Map<string, string>();
  for (const page of working) idByLower.set(page.id.toLowerCase(), page.id);

  const nameToId = new Map<string, string>();
  for (const page of working) {
    if (page.title) {
      const key = page.title.toLowerCase();
      if (!nameToId.has(key)) nameToId.set(key, page.id);
    }
  }
  for (const page of working) {
    for (const alias of page.aliases) {
      const key = alias.toLowerCase();
      if (!nameToId.has(key)) nameToId.set(key, page.id);
    }
  }

  return working.map((page): PageRegistryEntry => {
    const resolved = new Set<string>();
    const broken = new Set<string>();
    for (const target of page.rawLinks) {
      const resolvedId = resolveTarget(target, idByLower, nameToId);
      if (resolvedId) resolved.add(resolvedId);
      else broken.add(target);
    }
    return {
      id: page.id,
      path: page.path,
      title: page.title,
      type: page.type,
      aliases: page.aliases,
      sources: page.sources,
      links: [...resolved].sort(),
      brokenLinks: [...broken].sort(),
      headings: page.headings,
      excerpt: page.excerpt,
      mtimeMs: page.mtimeMs,
    };
  });
}

function resolveTarget(target: string, idByLower: Map<string, string>, nameToId: Map<string, string>): string | null {
  const trimmed = target.trim();
  if (trimmed.length === 0) return null;
  const normalized = normalizePathId(trimmed);
  if (normalized.length > 0) {
    const hit = idByLower.get(normalized.toLowerCase());
    if (hit) return hit;
  }
  return nameToId.get(trimmed.toLowerCase()) ?? null;
}

function normalizePathId(target: string): string {
  let t = target.replace(/\\/g, "/").replace(/^\/+/, "").replace(/\/+$/, "");
  if (/^wiki\//i.test(t)) t = t.replace(/^wiki\//i, "");
  t = t.replace(/\.md$/i, "").replace(/\/{2,}/g, "/");
  return t;
}

function collectSources(vaultRoot: string): SourceRegistryEntry[] {
  const sourcesRoot = path.join(vaultRoot, "raw", "sources");
  if (!fs.existsSync(sourcesRoot)) return [];
  const entries: SourceRegistryEntry[] = [];
  for (const name of fs.readdirSync(sourcesRoot).sort()) {
    if (!name.startsWith("SRC-")) continue;
    const dir = path.join(sourcesRoot, name);
    if (!fs.statSync(dir).isDirectory()) continue;
    const manifestFile = path.join(dir, MANIFEST_FILENAME);
    if (!fs.existsSync(manifestFile)) continue;
    let manifest: SourcePacketManifest;
    try {
      manifest = JSON.parse(fs.readFileSync(manifestFile, "utf8")) as SourcePacketManifest;
    } catch {
      continue;
    }
    entries.push(sourceEntryFromManifest(vaultRoot, dir, manifest));
  }
  return entries;
}

function sourceEntryFromManifest(
  vaultRoot: string,
  packetDir: string,
  manifest: SourcePacketManifest,
): SourceRegistryEntry {
  const origin = manifest.origin;
  const entry: SourceRegistryEntry = {
    id: manifest.id,
    path: toPosix(path.relative(vaultRoot, packetDir)),
    originType: origin.sourceType,
    title: origin.title?.trim() || null,
    contentHash: manifest.contentHash,
    ingestStatus: manifest.ingest.status,
    capturedAt: manifest.createdAt,
  };
  if (origin.sourceType === "url") entry.url = origin.url;
  if (origin.sourceType === "file") entry.originPath = origin.originPath;
  return entry;
}

interface PageTypeGroup {
  label: string;
  pages: PageRegistryEntry[];
}

function groupPagesByType(pages: PageRegistryEntry[]): PageTypeGroup[] {
  const byType = new Map<string, PageRegistryEntry[]>();
  for (const page of pages) {
    const key = page.type ?? "";
    getOrInitMap(byType, key, () => []).push(page);
  }

  const groups: PageTypeGroup[] = [];
  const pushGroup = (label: string, key: string): void => {
    const list = byType.get(key);
    if (list) groups.push({ label, pages: list.sort((a, b) => a.id.localeCompare(b.id)) });
  };

  for (const known of KNOWN_PAGE_TYPE_ORDER) pushGroup(known, known);
  for (const key of [...byType.keys()]
    .filter((k) => k !== "" && !(KNOWN_PAGE_TYPE_ORDER as readonly string[]).includes(k))
    .sort()) {
    pushGroup(key, key);
  }
  pushGroup("Unclassified", "");
  return groups;
}

function extractH1Headings(body: string): string[] {
  const out: string[] = [];
  for (const line of body.split("\n")) {
    if (/^#\s+/.test(line)) out.push(line.trim());
  }
  return out;
}

function makeExcerpt(body: string): string {
  const withoutLeadingH1 = body.replace(/^#\s+[^\n]*\n?/, "");
  const collapsed = withoutLeadingH1.replace(/\s+/g, " ").trim();
  return collapsed.length <= EXCERPT_MAX ? collapsed : collapsed.slice(0, EXCERPT_MAX);
}

function cleanStrings(values: string[] | undefined): string[] {
  const out: string[] = [];
  for (const value of values ?? []) {
    const trimmed = value.trim();
    if (trimmed.length > 0) out.push(trimmed);
  }
  return out;
}

function getOrInitMap<K, V>(map: Map<K, V>, key: K, init: () => V): V {
  const existing = map.get(key);
  if (existing !== undefined) return existing;
  const created = init();
  map.set(key, created);
  return created;
}

function getOrInitRecord(record: Record<string, string[]>, key: string): string[] {
  const existing = record[key];
  if (existing !== undefined) return existing;
  const created: string[] = [];
  record[key] = created;
  return created;
}

export function readEvents(eventsPath: string): unknown[] {
  return readJsonl(eventsPath);
}

interface RenderedEvent {
  date: string;
  time: string;
  text: string;
}

function renderEventLine(raw: unknown): RenderedEvent | null {
  if (raw === null || typeof raw !== "object") return null;
  const record = raw as Record<string, unknown>;
  const ts = typeof record.ts === "string" ? record.ts : "";
  const kind = typeof record.kind === "string" ? record.kind : "(event)";
  const summary = typeof record.summary === "string" ? record.summary : "";
  return {
    date: ts.slice(0, 10) || "unknown",
    time: ts.length >= 19 ? ts.slice(11, 19) : "--:--:--",
    text: summary.length > 0 ? `${kind} — ${summary}` : kind,
  };
}
