import * as path from "node:path";
import { atomicWriteFile } from "./atomic.ts";
import { type InboxFile, type InboxScan, scanInbox } from "./inbox.ts";
import { buildBacklinks, buildRegistry, type RegistryDoc } from "./meta.ts";
import { type CaptureInput, captureSource } from "./packet.ts";
import { vaultLayout } from "./paths.ts";

export type LintSeverity = "error" | "warning";

export type LintFindingKind =
  | "orphan_page"
  | "broken_wikilink"
  | "duplicate_alias"
  | "dangling_source_ref"
  | "uncovered_source"
  | "inbox_uncaptured"
  | "inbox_modified";

export interface LintFinding {
  kind: LintFindingKind;
  severity: LintSeverity;
  message: string;
  page?: string;
  source?: string;
  path?: string;
  aliases?: string[];
  detail?: Record<string, unknown>;
  fixable: boolean;
}

export interface LintSummary {
  total: number;
  errors: number;
  warnings: number;
  byKind: Record<LintFindingKind, number>;
}

export interface LintReport {
  vault: string;
  generatedAt: string;
  summary: LintSummary;
  findings: LintFinding[];
}

export interface LintOptions {
  now?: () => Date;
}

export interface LintFixResult {
  vault: string;
  captured: { relPath: string; packetId: string }[];
  remaining: number;
  report: LintReport;
}

export interface ApplyFixOptions {
  now?: () => Date;
}

const ORPHAN_EXEMPT_IDS = new Set(["overview"]);

const EMPTY_BY_KIND: Record<LintFindingKind, number> = {
  orphan_page: 0,
  broken_wikilink: 0,
  duplicate_alias: 0,
  dangling_source_ref: 0,
  uncovered_source: 0,
  inbox_uncaptured: 0,
  inbox_modified: 0,
};

const KIND_ORDER: readonly LintFindingKind[] = [
  "dangling_source_ref",
  "broken_wikilink",
  "duplicate_alias",
  "orphan_page",
  "uncovered_source",
  "inbox_uncaptured",
  "inbox_modified",
];

const KIND_LABELS: Record<LintFindingKind, string> = {
  orphan_page: "Orphan pages",
  broken_wikilink: "Broken wikilinks",
  duplicate_alias: "Duplicate aliases",
  dangling_source_ref: "Dangling source references",
  uncovered_source: "Uncovered sources",
  inbox_uncaptured: "Inbox — uncaptured files",
  inbox_modified: "Inbox — modified files",
};

export function lintVault(vaultRoot: string, opts: LintOptions = {}): LintReport {
  const generatedAt = (opts.now ?? (() => new Date()))().toISOString();
  const registry = buildRegistry(vaultRoot, opts);
  const backlinks = buildBacklinks(registry, opts);
  const inbox = scanInbox(vaultRoot);

  const findings: LintFinding[] = [
    ...findDanglingSourceRefs(registry),
    ...findBrokenWikilinks(registry),
    ...findDuplicateAliases(registry),
    ...findOrphanPages(registry, backlinks.backlinks),
    ...findUncoveredSources(registry),
    ...findInboxDrift(inbox),
  ];
  findings.sort(compareFindings);

  return { vault: vaultRoot, generatedAt, summary: summarize(findings), findings };
}

export function renderLintReportMd(report: LintReport): string {
  const lines: string[] = [
    "# Wiki Lint Report",
    "",
    `> Auto-generated by \`wiki_lint\` for ${report.vault}.`,
    `> Generated: ${report.generatedAt}`,
    "",
    `Total: ${report.summary.total} (${report.summary.errors} errors, ${report.summary.warnings} warnings)`,
  ];

  if (report.findings.length === 0) {
    lines.push("", "_No issues found._");
    return `${lines.join("\n")}\n`;
  }

  for (const kind of KIND_ORDER) {
    const group = report.findings.filter((f) => f.kind === kind);
    if (group.length === 0) continue;
    lines.push("", `## ${KIND_LABELS[kind]} (${group.length})`);
    for (const finding of group) {
      const tag = finding.severity === "error" ? "ERROR" : "warn";
      lines.push(`- ${tag}: ${finding.message}`);
    }
  }
  return `${lines.join("\n")}\n`;
}

export function writeLintReport(vaultRoot: string, report: LintReport): string {
  const lintReportPath = vaultLayout(vaultRoot).lintReport;
  atomicWriteFile(lintReportPath, renderLintReportMd(report));
  return lintReportPath;
}

export async function applyLintFixes(
  vaultRoot: string,
  report: LintReport,
  opts: ApplyFixOptions = {},
): Promise<LintFixResult> {
  const sourcesDir = vaultLayout(vaultRoot).sourcesRoot;
  const captured: { relPath: string; packetId: string }[] = [];

  for (const finding of report.findings) {
    if (finding.kind !== "inbox_uncaptured") continue;
    if (!finding.path) continue;
    const originPath = path.resolve(vaultRoot, finding.path);
    const input: CaptureInput = { sourceType: "file", originPath };
    const result = await captureSource(input, { sourcesDir, now: opts.now });
    captured.push({ relPath: finding.path, packetId: result.manifest.id });
  }

  const fresh = lintVault(vaultRoot, opts);
  return { vault: vaultRoot, captured, remaining: fresh.summary.total, report: fresh };
}

function findBrokenWikilinks(registry: RegistryDoc): LintFinding[] {
  const out: LintFinding[] = [];
  for (const page of registry.pages) {
    for (const target of page.brokenLinks) {
      out.push({
        kind: "broken_wikilink",
        severity: "warning",
        message: `Page [[${page.id}]] links to unresolved target "${target}".`,
        page: page.id,
        fixable: false,
        detail: { target },
      });
    }
  }
  return out;
}

function findDuplicateAliases(registry: RegistryDoc): LintFinding[] {
  const nameToPages = new Map<string, string[]>();
  const register = (name: string | null, pageId: string): void => {
    if (name === null) return;
    const key = name.trim().toLowerCase();
    if (key.length === 0) return;
    const list = nameToPages.get(key);
    if (list) {
      if (!list.includes(pageId)) list.push(pageId);
    } else {
      nameToPages.set(key, [pageId]);
    }
  };

  for (const page of registry.pages) {
    register(page.title, page.id);
    for (const alias of page.aliases) register(alias, page.id);
  }

  const out: LintFinding[] = [];
  for (const [name, pages] of nameToPages) {
    if (pages.length <= 1) continue;
    out.push({
      kind: "duplicate_alias",
      severity: "warning",
      message: `Name "${name}" is claimed by ${pages.length} pages: ${pages.join(", ")}.`,
      aliases: pages,
      fixable: false,
      detail: { name, pages },
    });
  }
  return out;
}

function findOrphanPages(registry: RegistryDoc, backlinks: Record<string, string[]>): LintFinding[] {
  if (registry.pages.length <= 1) return [];
  const out: LintFinding[] = [];
  for (const page of registry.pages) {
    if (ORPHAN_EXEMPT_IDS.has(page.id)) continue;
    const incoming = backlinks[page.id];
    if (!incoming || incoming.length === 0) {
      out.push({
        kind: "orphan_page",
        severity: "warning",
        message: `Page [[${page.id}]] has no incoming wikilinks (orphan).`,
        page: page.id,
        fixable: false,
      });
    }
  }
  return out;
}

function findDanglingSourceRefs(registry: RegistryDoc): LintFinding[] {
  const knownSourceIds = new Set(registry.sources.map((s) => s.id));
  const out: LintFinding[] = [];
  for (const page of registry.pages) {
    for (const cited of page.sources) {
      if (!knownSourceIds.has(cited)) {
        out.push({
          kind: "dangling_source_ref",
          severity: "error",
          message: `Page [[${page.id}]] cites unknown Source Packet "${cited}".`,
          page: page.id,
          source: cited,
          fixable: false,
          detail: { cited },
        });
      }
    }
  }
  return out;
}

function findUncoveredSources(registry: RegistryDoc): LintFinding[] {
  const cited = new Set<string>();
  for (const page of registry.pages) {
    for (const src of page.sources) cited.add(src);
  }
  const out: LintFinding[] = [];
  for (const source of registry.sources) {
    if (source.ingestStatus !== "ingested") continue;
    if (cited.has(source.id)) continue;
    out.push({
      kind: "uncovered_source",
      severity: "warning",
      message: `Source Packet ${source.id} is marked ingested but cited by no page.`,
      source: source.id,
      fixable: false,
    });
  }
  return out;
}

function findInboxDrift(inbox: InboxScan): LintFinding[] {
  const out: LintFinding[] = [];
  for (const file of inbox.uncaptured) {
    out.push(toInboxFinding(file, "inbox_uncaptured", "is not captured as a Source Packet", true));
  }
  for (const file of inbox.modified) {
    out.push(toInboxFinding(file, "inbox_modified", "has changed since capture (originHash drift)", false));
  }
  return out;
}

function toInboxFinding(
  file: InboxFile,
  kind: "inbox_uncaptured" | "inbox_modified",
  reason: string,
  fixable: boolean,
): LintFinding {
  return {
    kind,
    severity: "warning",
    message: `Inbox file "${file.relPath}" ${reason}.`,
    path: file.relPath,
    fixable,
  };
}

function summarize(findings: LintFinding[]): LintSummary {
  const byKind: Record<LintFindingKind, number> = { ...EMPTY_BY_KIND };
  let errors = 0;
  let warnings = 0;
  for (const finding of findings) {
    byKind[finding.kind] += 1;
    if (finding.severity === "error") errors += 1;
    else warnings += 1;
  }
  return { total: findings.length, errors, warnings, byKind };
}

function compareFindings(a: LintFinding, b: LintFinding): number {
  const byKind = KIND_ORDER.indexOf(a.kind) - KIND_ORDER.indexOf(b.kind);
  if (byKind !== 0) return byKind;
  const ak = a.page ?? a.source ?? a.path ?? "";
  const bk = b.page ?? b.source ?? b.path ?? "";
  if (ak !== bk) return ak < bk ? -1 : 1;
  if (a.message !== b.message) return a.message < b.message ? -1 : 1;
  return 0;
}
